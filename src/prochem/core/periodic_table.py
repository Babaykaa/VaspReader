ELEMENTS_BY_ATOMIC_NUMBER: dict[int, Element] = {
    item.atomic_number: item for item in ELEMENTS.values()
}


def normalize_symbol(symbol: str | int) -> str:
    """Return a canonical element symbol spelling."""
    if isinstance(symbol, bool):
        raise ValueError("Element atomic number must be an integer, got bool.")
    if isinstance(symbol, int):
        item = ELEMENTS_BY_ATOMIC_NUMBER.get(symbol)
        if item is None:
            raise ValueError(f"Unknown element atomic number: {symbol}.")
        return item.symbol

    value = str(symbol).strip()
    if not value:
        raise ValueError("Element symbol cannot be empty.")
    if value.isdigit():
        item = ELEMENTS_BY_ATOMIC_NUMBER.get(int(value))
        if item is None:
            raise ValueError(f"Unknown element atomic number: {value}.")
        return item.symbol
    return value[0].upper() + value[1:].lower()


def element(symbol: str | int) -> Element | None:
    """Return metadata for an element symbol when it is known."""
    return ELEMENTS.get(normalize_symbol(symbol))


def atomic_mass(symbol: str | int) -> float | None:
    item = element(symbol)
    return None if item is None else item.mass


def covalent_radius(symbol: str | int) -> float | None:
    item = element(symbol)
    return None if item is None else item.covalent_radius


def vdw_radius(symbol: str | int) -> float | None:
    item = element(symbol)
    return None if item is None else item.vdw_radius


def valence_charge(symbol: str | int) -> int | None:
    item = element(symbol)
    return None if item is None else item.valence_charge


